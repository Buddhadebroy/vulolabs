	public static function emoji_flag( $iso_code ) {
		$iso_code = strtoupper( (string) $iso_code );

		if ( 2 !== strlen( $iso_code ) ) {
			return $iso_code;
		}

		$flag = '';
		for ( $i = 0; $i < 2; $i++ ) {
			$flag .= mb_chr( 0x1F1E6 + ( ord( $iso_code[ $i ] ) - ord( 'A' ) ), 'UTF-8' );
		}

		return $flag;
	}
